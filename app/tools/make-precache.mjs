// Writes precache.js, the list of files the service worker keeps for offline use:
//   node tools/make-precache.mjs
// test/sw.test.js fails when it's out of date, i.e. after adding or removing an app file.
import { createHash } from "node:crypto";
import { readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { STORAGE_ID } from "../src/app-info.js";

const root = new URL("../", import.meta.url);

const listFiles = async (dir) => {
	const out = [];
	for (const entry of await readdir(new URL(dir, root), { withFileTypes: true })) {
		const path = `${dir}${entry.name}`;
		if (entry.isDirectory()) out.push(...(await listFiles(`${path}/`)));
		else out.push(path);
	}
	return out;
};

/** Every file the app loads, as the page requests them. */
export const appFiles = async () =>
	[
		"./",
		"index.html",
		"styles.css",
		"manifest.webmanifest",
		...(await listFiles("icons/")),
		...(await listFiles("fonts/")),
		...(await listFiles("src/")).filter((p) => p.endsWith(".js")),
	].sort();

export const buildPrecache = async () => {
	const files = await appFiles();
	// The version follows the file list, not file contents: fetches are network-first, so
	// changed files refresh on their own, but a renamed or deleted file only leaves the cache
	// when the cache itself is replaced.
	const version = createHash("sha256").update(files.join("\n")).digest("hex").slice(0, 12);
	return `// Generated by tools/make-precache.mjs. Don't edit by hand.
self.CACHE_NAME = "${STORAGE_ID}-${version}";
self.PRECACHE = ${JSON.stringify(files, null, "\t")};
`;
};

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	await writeFile(new URL("precache.js", root), await buildPrecache());
	console.log("precache.js written");
}
